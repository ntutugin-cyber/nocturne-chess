// Оценка в сантипешках, положительная = лучше белым
export function evaluate(pos) {
  const b = pos.board;
  let score = 0, phaseMat = 0, wB = 0, bB = 0;
  const pieces = [];
  for (let s = 0; s < 128; s++) {
    if (s & 0x88) { s += 7; continue; }
    const p = b[s];
    if (!p) continue;
    const t = Math.abs(p), c = Math.sign(p);
    if (t !== KING && t !== PAWN) phaseMat += VALUES[t];
    pieces.push([s, t, c]);
  }
  const endgame = phaseMat < 2400;
  for (const [s, t, c] of pieces) {
    const f = s & 15, r = s >> 4;
    const idx = c === WHITE ? (7 - r) * 8 + f : r * 8 + f;
    let v = VALUES[t];
    if (t === KING) v += endgame ? PST_KE[idx] : PST_KM[idx];
    else v += PST[t][idx];
    if (t === BISHOP) { if (c === WHITE) wB++; else bB++; }
    score += c * v;
  }
  if (wB >= 2) score += 30;
  if (bB >= 2) score -= 30;
  return score;
}

